// Parse the inactive template using the already locked upstream dev dependency; no extra install.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { actionRoot } from './action-context.mjs';
import pathModule from 'node:path';
const require = createRequire(pathModule.join(actionRoot, 'package.json'));
const { parseDocument } = require('yaml');
const path = fileURLToPath(new URL('../manual-release.workflow.yml', import.meta.url));
const document = parseDocument(readFileSync(path, 'utf8'));
assert.deepEqual(document.errors, []);
const workflow = document.toJS();
assert.deepEqual(Object.keys(workflow.on), ['workflow_dispatch']);
assert.equal(workflow.on.workflow_dispatch.inputs.mode.default, 'dry-run');
assert.equal(workflow.concurrency['cancel-in-progress'], false);
assert.deepEqual(workflow.permissions, { contents: 'read' });
const job = workflow.jobs['prepare-and-run'];
assert.ok(job['runs-on'].includes('self-hosted'));
assert.ok(job['runs-on'].includes('Windows'));
for (const step of job.steps.filter(s => s.uses)) assert.match(step.uses, /@[0-9a-f]{40}$/);
const official = job.steps.find(s => s.with?.repository === 'Nexus-Mods/upload-action');
assert.equal(official.with.ref, '98532f7670c27cbecc78fae03fa3e278147827e2');
const run = job.steps.find(s => s.run?.includes('publish.py'));
assert.ok(run.run.includes("if ($env:MODE -eq 'publish')"));
assert.equal(run.env.NEXUS_STATE_DIR, '${{ vars.NEXUS_STATE_DIR }}');
assert.ok(run.run.includes('IsPathFullyQualified'));
assert.ok(run.run.includes('--state-dir'));
assert.doesNotMatch(run.run, /['"][A-Za-z]:[\\/]/);
console.log('Manual workflow YAML parses; dispatch-only, dry-run default, immutable pins and durable ledger checked.');
